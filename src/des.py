"""A discrete-event simulation of a multi-server queue with abandonment.

One engine, driven by whatever distributions it is handed. The system being
studied and the simplified model of it are both run through this, so any
difference between them comes from the assumptions rather than from two
separate pieces of code behaving differently.

Events are kept in a heap. A customer who is still waiting when their patience
runs out abandons. Abandonment events for customers who have already started
service are left in the heap and ignored when they come up, which is cheaper
than removing them.
"""

import heapq
from collections import deque

import numpy as np

ARRIVAL, DEPARTURE, ABANDON = 0, 1, 2

WAITING, IN_SERVICE, DONE, ABANDONED = 0, 1, 2, 3


def arrival_times(n, rate_fn, rate_max, rng):
    """Arrival times of n customers from a Poisson process with time-varying rate.

    Generated by thinning: propose from a Poisson process at the maximum rate
    and keep each proposal with probability rate(t) / rate_max.
    """
    times = []
    t = 0.0
    while len(times) < n:
        t += rng.exponential(1.0 / rate_max)
        if rng.random() <= rate_fn(t) / rate_max:
            times.append(t)
    return np.array(times)


def simulate(n_customers, n_servers, rate_fn, rate_max,
             service_sampler, patience_sampler, rng, arrivals=None):
    """Run the queue and return per-customer results.

    service_sampler and patience_sampler are callables taking rng and
    returning one duration. patience_sampler may be None, meaning nobody
    ever gives up and leaves. arrivals lets a caller supply exact arrival
    times instead of drawing them, which is what the tests use to get a
    case whose answer can be worked out by hand.
    """
    if n_servers < 1:
        raise ValueError("need at least one server")

    if arrivals is None:
        arrive = arrival_times(n_customers, rate_fn, rate_max, rng)
    else:
        arrive = np.asarray(arrivals, dtype=float)
        if arrive.size != n_customers:
            raise ValueError("arrivals must have one time per customer")

    status = np.full(n_customers, WAITING, dtype=int)
    wait = np.full(n_customers, np.nan)
    start = np.full(n_customers, np.nan)
    end = np.full(n_customers, np.nan)
    patience = np.full(n_customers, np.inf)

    events = [(float(arrive[i]), ARRIVAL, i) for i in range(n_customers)]
    heapq.heapify(events)

    queue = deque()
    free = n_servers

    def start_service(i, now):
        nonlocal free
        free -= 1
        status[i] = IN_SERVICE
        wait[i] = now - arrive[i]
        start[i] = now
        finish = now + service_sampler(rng)
        end[i] = finish
        heapq.heappush(events, (finish, DEPARTURE, i))

    while events:
        now, kind, i = heapq.heappop(events)

        if kind == ARRIVAL:
            if free > 0:
                start_service(i, now)
            else:
                queue.append(i)
                if patience_sampler is not None:
                    p = patience_sampler(rng)
                    patience[i] = p
                    heapq.heappush(events, (now + p, ABANDON, i))

        elif kind == ABANDON:
            if status[i] == WAITING:
                status[i] = ABANDONED
                wait[i] = now - arrive[i]

        else:
            free += 1
            status[i] = DONE
            while queue:
                j = queue.popleft()
                if status[j] == WAITING:
                    start_service(j, now)
                    break

    return {
        "arrive": arrive,
        "wait": wait,
        "start": start,
        "end": end,
        "status": status,
        "served": status == DONE,
        "abandoned": status == ABANDONED,
    }


def max_concurrent(res):
    """Largest number of customers in service at any one moment."""
    s = res["start"]
    e = res["end"]
    ok = np.isfinite(s) & np.isfinite(e)
    if not ok.any():
        return 0
    marks = [(t, 1) for t in s[ok]] + [(t, -1) for t in e[ok]]
    marks.sort(key=lambda m: (m[0], m[1]))
    cur = peak = 0
    for _, d in marks:
        cur += d
        peak = max(peak, cur)
    return peak


def summarise(res):
    """Headline numbers an operations team would actually look at."""
    served = res["served"]
    w = res["wait"][served]
    n = len(res["status"])
    return {
        "mean_wait": float(np.mean(w)) if w.size else float("nan"),
        "p95_wait": float(np.percentile(w, 95)) if w.size else float("nan"),
        "abandon_rate": float(res["abandoned"].sum() / n),
        "n": int(n),
    }
